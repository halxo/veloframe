export function generateBenchmarkSlides(count: number, theme: ThemeDefinition): Slide[] {
  const slides: Slide[] = [];
  const accents = ['#0057FF', '#0F766E', '#C84B31', '#D97706', '#2563EB', '#059669'];

  for (let i = 0; i < count; i++) {
    const accent = accents[i % accents.length];
    const slideNum = i + 1;
    const nodes: SceneNode[] = [
      makeRect({
        name: 'Top Accent Strip',
        x: 0,
        y: 0,
        width: SLIDE_WIDTH,
        height: 14,
        fill: accent,
        cornerRadius: 0,
      }),
      makeText({
        name: 'Benchmark Heading',
        x: 120,
        y: 90,
        width: 1400,
        height: 96,
        text: `Stress Test Slide #${slideNum}`,
        fontFamily: theme.headingFont,
        fontSize: 58,
        fontWeight: 800,
        letterSpacing: -1.5,
        color: theme.ink,
        padding: 0,
      }),
    ];

    // Add 12 vector cards/shapes per slide to verify R-tree & dirty-rect speed
    for (let j = 0; j < 6; j++) {
      const col = j % 3;
      const row = Math.floor(j / 3);
      const x = 120 + col * 580;
      const y = 240 + row * 380;
      nodes.push(
        makeRect({
          name: `Metric Tile ${j + 1}`,
          x,
          y,
          width: 520,
          height: 320,
          fill: theme.surface,
          stroke: theme.surfaceBorder,
          strokeWidth: 2,
          cornerRadius: 20,
        }),
        makeText({
          name: `Metric Text ${j + 1}`,
          x: x + 36,
          y: y + 40,
          width: 448,
          height: 220,
          text: `${((slideNum * 17 + j * 13) % 99) + 1}.${(j * 3) % 10}%\nNode ${slideNum}.${j + 1}`,
          fontFamily: theme.headingFont,
          fontSize: 48,
          fontWeight: 700,
          lineHeight: 1.3,
          color: j === 0 ? accent : theme.ink,
          padding: 0,
        }),
      );
    }

    slides.push({
      id: uid('slide'),
      background: { ...theme.background },
      transition: i % 2 === 0 ? 'fade' : 'slide',
      transitionDurationMs: 360,
      notes: `Benchmark slide ${slideNum} of ${count}.`,
      nodes,
    });
  }

  return slides;
}
