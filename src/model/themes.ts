function makeText(overrides: Partial<TextNode> & { text: string; x: number; y: number; width: number; height: number }): TextNode {
  return {
    id: overrides.id ?? uid('txt'),
    type: 'text',
    name: overrides.name ?? 'Text Box',
    x: overrides.x,
    y: overrides.y,
    width: overrides.width,
    height: overrides.height,
    rotation: overrides.rotation ?? 0,
    opacity: overrides.opacity ?? 1,
    shadow: overrides.shadow ?? createDefaultShadow(),
    groupId: overrides.groupId ?? null,
    locked: overrides.locked ?? false,
    text: overrides.text,
    fontFamily: overrides.fontFamily ?? 'Inter, system-ui, sans-serif',
    fontSize: overrides.fontSize ?? 32,
    fontWeight: overrides.fontWeight ?? 400,
    fontStyle: overrides.fontStyle ?? 'normal',
    textAlign: overrides.textAlign ?? 'left',
    verticalAlign: overrides.verticalAlign ?? 'top',
    lineHeight: overrides.lineHeight ?? 1.35,
    letterSpacing: overrides.letterSpacing ?? 0,
    color: overrides.color ?? '#141517',
    fill: overrides.fill ?? 'transparent',
    stroke: overrides.stroke ?? 'transparent',
    strokeWidth: overrides.strokeWidth ?? 0,
    cornerRadius: overrides.cornerRadius ?? 0,
    padding: overrides.padding ?? 12,
  };
}

