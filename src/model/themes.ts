function makeArrow(overrides: Partial<LineNode> & { x: number; y: number; width: number; height: number }): LineNode {
  return {
    id: overrides.id ?? uid('arrow'),
    type: overrides.type ?? 'arrow',
    name: overrides.name ?? 'Arrow',
    x: overrides.x,
    y: overrides.y,
    width: overrides.width,
    height: overrides.height,
    rotation: overrides.rotation ?? 0,
    opacity: overrides.opacity ?? 1,
    shadow: overrides.shadow ?? createDefaultShadow(),
    groupId: overrides.groupId ?? null,
    locked: overrides.locked ?? false,
    x1: overrides.x1 ?? 0,
    y1: overrides.y1 ?? overrides.height * 0.5,
    x2: overrides.x2 ?? overrides.width,
    y2: overrides.y2 ?? overrides.height * 0.5,
    stroke: overrides.stroke ?? '#0057FF',
    strokeWidth: overrides.strokeWidth ?? 5,
    dashed: overrides.dashed ?? false,
    arrowStart: overrides.arrowStart ?? false,
    arrowEnd: overrides.arrowEnd ?? true,
  };
}

